/** An operation both kits have, which the front may have a backend spell. */
export type SharedOp = (typeof SHARED)[number] | keyof typeof RENAMED;
/** Every operation both kits have. */
export const SHARED_OPS: readonly SharedOp[] = [...SHARED, ...(Object.keys(RENAMED) as (keyof typeof RENAMED)[])];
export type SwiftOp = SharedOp | (typeof SWIFT_ONLY)[number];
export type KotlinOp = SharedOp | (typeof KOTLIN_ONLY)[number];
export type RuntimeOp = SwiftOp | KotlinOp;

export type RuntimeColumn<Op extends string> = { readonly [K in Op]: string };

function column<Op extends string>(ops: readonly Op[], names: Readonly<Partial<Record<string, string>>> = {}): RuntimeColumn<Op> {
	return Object.freeze(Object.fromEntries(ops.map((op) => [op, names[op] ?? op]))) as RuntimeColumn<Op>;
}

export const SWIFT_RUNTIME: RuntimeColumn<SwiftOp> = column<SwiftOp>([...SHARED, ...(Object.keys(RENAMED) as (keyof typeof RENAMED)[]), ...SWIFT_ONLY]);
export const KOTLIN_RUNTIME: RuntimeColumn<KotlinOp> = column<KotlinOp>([...SHARED, ...(Object.keys(RENAMED) as (keyof typeof RENAMED)[]), ...KOTLIN_ONLY], RENAMED);
